#!/usr/bin/env python3
"""Generate per-category colour themes for Gamato Piranti.

Tailwind v4 exposes every palette colour as a CSS variable (--color-indigo-600 …). The whole app is styled
with the indigo/violet utilities, so re-pointing those variables per category re-colours every tool of that
category without touching a single component. Lightness of each step is copied from Tailwind's indigo/violet
scale -> WCAG contrast of text/background combinations is identical to the audited default theme. Chroma is
clamped to the sRGB gamut so low-chroma hues (amber, teal) never get clipped into muddy colours."""
import math

INDIGO = {50:(96.2,.018,272.314),100:(93,.034,272.788),200:(87,.065,274.039),300:(78.5,.115,274.713),400:(67.3,.182,276.935),
          500:(58.5,.233,277.117),600:(51.1,.262,276.966),700:(45.7,.24,277.023),800:(39.8,.195,277.366),900:(35.9,.144,278.697),950:(25.7,.09,281.288)}
VIOLET = {50:(96.9,.016,293.756),100:(94.3,.029,294.588),200:(89.4,.057,293.283),300:(81.1,.111,293.571),400:(70.2,.183,293.541),
          500:(60.6,.25,292.717),600:(54.1,.281,293.009),700:(49.1,.27,292.581),800:(43.2,.232,292.759),900:(38,.189,293.745),950:(28.3,.141,291.089)}

# theme id -> (primary hue, companion hue)
THEMES = {
  "kode":     (182, 208),
  "dokumen":  (250, 278),
  "office":   (296, 330),
  "gambar":   (48, 18),
  "video":    (14, 44),
  "audio":    (214, 248),
  "utilitas": (346, 310),
  "spesial":  (70, 42),
}

def oklch_to_srgb(L, C, H):
    h = math.radians(H); a = C*math.cos(h); b = C*math.sin(h)
    l_ = L + 0.3963377774*a + 0.2158037573*b
    m_ = L - 0.1055613458*a - 0.0638541728*b
    s_ = L - 0.0894841775*a - 1.2914855480*b
    l, m, s = l_**3, m_**3, s_**3
    return (4.0767416621*l - 3.3077115913*m + 0.2309699292*s,
            -1.2684380046*l + 2.6097574011*m - 0.3413193965*s,
            -0.0041960863*l - 0.7034186147*m + 1.7076147010*s)

def in_gamut(L, C, H):
    return all(-0.0005 <= v <= 1.0005 for v in oklch_to_srgb(L, C, H))

def max_chroma(L, H):
    lo, hi = 0.0, 0.4
    for _ in range(30):
        mid = (lo+hi)/2
        if in_gamut(L, mid, H): lo = mid
        else: hi = mid
    return lo

def remap(scale, base_hue, new_hue, name):
    out = []
    for step, (L, C, H) in scale.items():
        nh = new_hue + (H - base_hue)
        c = min(C, max_chroma(L/100, nh) * 0.96)
        out.append(f"  --color-{name}-{step}: oklch({L}% {c:.3f} {nh:.1f});")
    return "\n".join(out)

css = ["/* ── GENERATED by tools/gen-theme-css.py — jangan edit manual ──\n   Tema warna per kategori. <html data-gp-theme=\"…\"> diatur oleh Layout. */"]
for tid, (h1, h2) in THEMES.items():
    css.append(f'html[data-gp-theme="{tid}"] {{\n{remap(INDIGO, 277, h1, "indigo")}\n{remap(VIOLET, 293, h2, "violet")}\n}}')
open("src/theme.generated.css", "w").write("\n".join(css) + "\n")
print("ok", len(THEMES), "themes")
# sanity: print 600 step per theme
for tid,(h1,h2) in THEMES.items():
    L,C,H = INDIGO[600]; print(tid, round(min(C, max_chroma(L/100,h1)*0.96),3))
